import XLSX from 'xlsx';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CITY_PROFILES } from './city-profiles.mjs';

// One-time (re-run as needed) extraction of IBG_Target_Cities_Resource_Links_1.xlsx
// into lib/city-resource-links.ts. The sheet is small (427 rows, 3 short URLs
// each) and changes rarely, so it's a static TS module rather than a DB table —
// avoids a second DB round trip on every page render for near-constant data.
const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const wb = XLSX.readFile(path.join(rootDir, 'IBG_Target_Cities_Resource_Links_1.xlsx'));
const rows = XLSX.utils.sheet_to_json(wb.Sheets['Target Cities']);

// Match every row to a citySlug via (city name, state) — Birmingham is
// hand-tuned and not in CITY_PROFILES, so it's added manually.
const bySlug = { 'birmingham|Alabama': 'birmingham-al' };
for (const p of Object.values(CITY_PROFILES)) {
  bySlug[`${p.city.toLowerCase()}|${p.state}`] = p.citySlug;
}

let matched = 0;
const unmatched = [];
const links = {};
for (const row of rows) {
  const key = `${row['City'].toLowerCase()}|${row['State']}`;
  const slug = bySlug[key];
  if (!slug) { unmatched.push(`${row['City']}, ${row['State']}`); continue; }
  matched++;
  links[slug] = {
    chamberUrl: row['Local Chamber of Commerce URL'] || null,
    citySiteUrl: row['City Official / Tourism Website'] || null,
    stateCommerceUrl: row['State Dept. of Commerce URL'] || null,
  };
}

// pomona-ca-1 is a duplicate slug for West Covina, CA (upstream slug-collision
// quirk, same real city as west-covina-ca) — reuse its links rather than
// leave it empty. stamford-ct-1 (Norwalk, CT) and lewisville-tx-1 (Sugar
// Land, TX) have no matching row and are deliberately left without data
// rather than guessing unverified URLs.
if (links['west-covina-ca']) links['pomona-ca-1'] = links['west-covina-ca'];

const sbaRow = rows[0];
const sbaLinks = [
  { label: 'Plan Your Business', url: sbaRow['SBA: Plan Your Business'] },
  { label: 'Launch Your Business', url: sbaRow['SBA: Launch Your Business'] },
  { label: 'Manage Your Business', url: sbaRow['SBA: Manage Your Business'] },
  { label: 'Grow Your Business', url: sbaRow['SBA: Grow Your Business'] },
];

console.log(`Matched ${matched}/${rows.length} rows. Unmatched (${unmatched.length}):`, unmatched);
console.log(`Total city entries written: ${Object.keys(links).length}`);

const header = `// Generated by scripts/extract-resource-links.mjs from
// IBG_Target_Cities_Resource_Links_1.xlsx — do not hand-edit; re-run the
// script if the source sheet changes.

export interface CityResourceLinks {
  chamberUrl: string | null;
  citySiteUrl: string | null;
  stateCommerceUrl: string | null;
}

export interface SbaLink {
  label: string;
  url: string;
}

export const SBA_LINKS: SbaLink[] = ${JSON.stringify(sbaLinks, null, 2)};

export const CITY_RESOURCE_LINKS: Record<string, CityResourceLinks> = ${JSON.stringify(links, null, 2)};

export function getCityResourceLinks(citySlug: string): CityResourceLinks | undefined {
  return CITY_RESOURCE_LINKS[citySlug];
}
`;

await fs.writeFile(path.join(rootDir, 'lib/city-resource-links.ts'), header);
console.log('Wrote lib/city-resource-links.ts');
